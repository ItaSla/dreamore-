const LOWER_CONNECTORS = new Set(["of", "the", "and", "de", "del", "la", "las", "los", "y", "for", "with"]);

export function autoTranslatePhrase(text, targetLang) {
  const clean = String(text || "").trim();
  if (!clean || targetLang === "pt") return clean;
  let out = clean;
  const col = targetLang === "en" ? 1 : 2;
  for (const row of AUTO_PHRASES) {
    const escaped = row[0].replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, "giu");
    out = out.replace(regex, (match) => {
      const rep = row[col];
      const upperWords = (match.match(/(?<![\p{L}\p{N}])\p{Lu}/gu) || []).length;
      if (upperWords > 1 && rep.includes(" ")) {
        return rep
          .split(" ")
          .map((w, idx) => (idx === 0 || !LOWER_CONNECTORS.has(w) ? w[0].toUpperCase() + w.slice(1) : w))
          .join(" ");
      }
      const startsUpper = match[0] && match[0] === match[0].toUpperCase() && match[0] !== match[0].toLowerCase();
      return startsUpper ? rep[0].toUpperCase() + rep.slice(1) : rep;
    });
  }
  return out;
}

export function buildMultilingualFields(ptTitle, ptSynopsis) {
  return {
    title: {
      pt: ptTitle,
      en: autoTranslatePhrase(ptTitle, "en"),
      es: autoTranslatePhrase(ptTitle, "es"),
    },
    synopsis: {
      pt: ptSynopsis,
      en: autoTranslatePhrase(ptSynopsis, "en"),
      es: autoTranslatePhrase(ptSynopsis, "es"),
    },
  };
}

export function detectBrowserLanguage() {
  if (typeof navigator === "undefined") return "pt";
  const raw = String(navigator.language || "pt").toLowerCase();
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("en")) return "en";
  return "pt";
}

export function getText(lang, key) {
  return (UI_TEXT[lang] && UI_TEXT[lang][key]) || UI_TEXT.pt[key] || key;
}

export function getLocalizedField(mapObj, lang) {
  if (!mapObj) return "";
  if (typeof mapObj === "string") {
    return lang && lang !== "pt" ? autoTranslatePhrase(mapObj, lang) : mapObj;
  }
  const direct = mapObj[lang];
  const base = mapObj.pt || mapObj.en || "";
  if (lang && lang !== "pt") {
    if (!direct || direct.trim() === base.trim()) {
      return autoTranslatePhrase(base, lang);
    }
    return direct;
  }
  return direct || base;
}

